// Writes docs/en/ui-kit-reference.md and docs/ru/ui-kit-reference.md from the catalog the MCP server gives agents:
// one source for all of them.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { catalogText } from "../packages/sdk/src/catalog.ts";
import { symbols } from "../packages/sdk/src/validate.ts";

for (const lang of ["en", "ru"] as const) {
  const out = fileURLToPath(new URL(`../docs/${lang}/ui-kit-reference.md`, import.meta.url));
  writeFileSync(out, "<!-- Generated by scripts/gen-docs.ts from packages/sdk/src/catalog.ts: edit that, then npm run docs. -->\n\n" + catalogText([...symbols()].sort(), lang));
  console.log(out);
}
